from pydantic import BaseModel, Field, field_validator


class SalesActionPlan(BaseModel):
    """
    Structured sales guidance for a qualified lead, generated by the AI layer
    in backend/services/sales_plan_service.py.

    This is validated strictly (missing/invalid required fields raise a
    ValidationError) so the caller can catch that and fall back to the
    deterministic plan builder, exactly like the ai_service.py pattern for
    the qualification assessment itself.

    This model is advisory sales guidance only - it never sets score,
    classification, or any other deterministically-computed qualification
    field. next_action and recommended_offer are overwritten by
    sales_plan_service.py with the values already produced by the
    deterministic scoring/recommendation engine before validation, so they
    can never drift from the rest of the qualification result.
    """

    next_action: str
    approach: str
    communication_strategy: str
    meeting_objective: str
    talking_points: list[str] = Field(default_factory=list)
    discovery_questions: list[str] = Field(default_factory=list)
    pain_points_to_validate: list[str] = Field(default_factory=list)
    recommended_offer: str
    recommended_team: list[str] = Field(default_factory=list)
    possible_objections: list[str] = Field(default_factory=list)
    objection_handling: list[str] = Field(default_factory=list)
    after_meeting_actions: list[str] = Field(default_factory=list)
    information_to_collect: list[str] = Field(default_factory=list)
    success_criteria: list[str] = Field(default_factory=list)
    follow_up_plan: str

    @field_validator(
        "talking_points", "discovery_questions", "pain_points_to_validate",
        "recommended_team", "possible_objections", "objection_handling",
        "after_meeting_actions", "information_to_collect", "success_criteria",
        mode="before",
    )
    @classmethod
    def _coerce_list_of_str(cls, v):
        """Defensive normalization: accept a bare string or None from a
        slightly-off LLM response instead of hard-failing validation."""
        if v is None:
            return []
        if isinstance(v, str):
            return [v.strip()] if v.strip() else []
        if isinstance(v, list):
            return [str(item).strip() for item in v if str(item).strip()]
        return []

    @field_validator(
        "next_action", "approach", "communication_strategy", "meeting_objective",
        "recommended_offer", "follow_up_plan",
        mode="before",
    )
    @classmethod
    def _coerce_str(cls, v):
        if v is None:
            raise ValueError("required string field was null")
        text = str(v).strip()
        if not text:
            raise ValueError("required string field was empty")
        return text
